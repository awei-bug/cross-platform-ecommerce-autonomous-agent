import { chromium, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const token = await readFile(process.env.CHAIN_ADMIN_TOKEN_FILE, 'utf8')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
    const context = await browser.newContext({ viewport })
    await context.addInitScript((tokenValue) => sessionStorage.setItem('token', tokenValue), token)
    const page = await context.newPage()
    await page.goto(process.env.CHAIN_ADMIN_URL)
    if (viewport.width < 700) await page.getByRole('button', { name: '打开导航' }).click()
    await page.getByText('商品', { exact: true }).first().click()
    await page.getByText('商品列表', { exact: true }).first().click()
    await page.getByRole('button', { name: '商品同步记录' }).click()
    const section = page.getByRole('region', { name: '商品同步记录' })
    await expect(section.getByText('最近记录：', { exact: false })).toBeVisible()
    const row = section.locator('tr').filter({ hasText: process.env.CHAIN_EXTERNAL_ID })
    await expect(row).toContainText(process.env.CHAIN_PRODUCT_TITLE)
    await expect(row).toContainText('已上架')
    await expect(section.getByText('记录时间不代表同步进程当前在线', { exact: false })).toBeVisible()
    const pendingRow = section.locator('tr').filter({ hasText: '待补价演示杯' })
    if (viewport.width === 1440) {
      const issues = section.getByRole('region', { name: '同步失败商品' })
      await expect(issues).toContainText('cc-conflict-demo')
      await expect(issues).toContainText('本店存在同名商品')
      const existing = page.locator('tr').filter({ hasText: '冲突测试杯' }).filter({ has: page.getByRole('button', { name: '编辑' }) }).first()
      await existing.getByRole('button', { name: '编辑' }).click()
      const edit = page.getByRole('dialog', { name: '编辑商品' })
      await edit.locator('input').first().fill('已核对的本地商品')
      await edit.getByRole('button', { name: '保存' }).click()
      await expect(edit).toBeHidden()
      await expect(pendingRow).toContainText('待补价')
      await pendingRow.getByRole('button', { name: '补售价' }).click()
      const dialog = page.getByRole('dialog', { name: '补充商品售价' })
      await dialog.getByRole('textbox').fill('88.50')
      await dialog.getByRole('button', { name: '创建草稿' }).click()
      await expect.poll(async () => {
        await section.getByRole('button', { name: '刷新' }).click()
        return section.locator('tr').filter({ hasText: 'cc-conflict-demo' }).count()
      }, { timeout: 45000, intervals: [2000] }).toBeGreaterThan(0)
      await expect(section.locator('tr').filter({ hasText: 'cc-conflict-demo' })).toContainText('草稿/下架')
    }
    await expect(pendingRow).toContainText('草稿/下架')
    const nativeContext = await browser.newContext({ viewport })
    const nativePage = await nativeContext.newPage()
    await nativePage.goto(process.env.CHAIN_ADMIN_URL + '/login')
    await nativePage.getByPlaceholder('demo').fill('chain-test')
    await nativePage.getByPlaceholder('admin').fill('测试管理员')
    await nativePage.getByPlaceholder('密码').fill('test-only-password')
    await nativePage.getByRole('button', { name: '进入工作台' }).click()
    await expect(nativePage.getByRole('button', { name: '退出', exact: true })).toBeVisible()
    if (viewport.width < 700) await nativePage.getByRole('button', { name: '打开导航' }).click()
    await nativePage.getByText('内容中心', { exact: true }).first().click()
    await expect(nativePage.getByRole('heading', { name: '内容中心' })).toBeVisible()
    await expect(nativePage.getByText('一键自动上架', { exact: true })).toBeVisible()
    if (viewport.width < 700) await nativePage.getByRole('button', { name: '打开导航' }).click()
    await nativePage.getByText('自动化运营中心', { exact: true }).first().click()
    await expect(nativePage.getByRole('heading', { name: '自动化运营中心' })).toBeVisible()
    await expect(nativePage.getByRole('heading', { name: '运营检查' })).toBeVisible()
    await expect(nativePage.getByText('商品上架完整度检查')).toBeVisible()
    if (viewport.width === 1440) {
      await nativePage.locator('tr').filter({ hasText: '商品上架完整度检查' }).getByRole('button', { name: '运行检查' }).click()
      await expect(nativePage.getByText('检查已执行')).toBeVisible()
      await expect(nativePage.getByRole('heading', { name: '最近运行记录' })).toBeVisible()
    }
    await nativePage.getByRole('tab', { name: '运营助手' }).click()
    await expect(nativePage.getByRole('heading', { name: '运营助手' })).toBeVisible()
    await expect(nativePage.getByPlaceholder('例如：上架纯棉T恤，89元，库存30')).toBeVisible()
    await nativePage.goto(process.env.CHAIN_ADMIN_URL + '/agent_ops')
    await expect(nativePage).toHaveURL(/operations_center\?tab=assistant/)
    await expect(nativePage.getByRole('heading', { name: '运营助手' })).toBeVisible()
    if (await nativePage.locator('iframe').count()) throw new Error('原生商家工作台不应嵌套其他系统')
    if (viewport.width < 700) await nativePage.getByRole('button', { name: '打开导航' }).click()
    await nativePage.getByText('客服', { exact: true }).click()
    await nativePage.getByText('客服知识库', { exact: true }).click()
    await expect(nativePage).toHaveURL(/knowledge_base/)
    if (viewport.width < 700) await nativePage.getByRole('button', { name: '打开导航' }).click()
    await nativePage.getByText('设置', { exact: true }).click()
    await nativePage.getByText('员工与权限', { exact: true }).click()
    await expect(nativePage).toHaveURL(/user_list/)
    if (process.env.CHAIN_SCREENSHOT_DIR) await nativePage.screenshot({ path: `${process.env.CHAIN_SCREENSHOT_DIR}/native-${viewport.width}.png` })
    await nativeContext.close()
    console.log(`PASS 商家后台 ${viewport.width}px：同步记录与实际商品上架状态`)
    await context.close()
  }
} finally { await browser.close() }
